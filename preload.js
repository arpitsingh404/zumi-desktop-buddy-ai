const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("zumi", {
  getSettings: () => ipcRenderer.invoke("settings:get"),
  setSettings: (patch) => ipcRenderer.invoke("settings:set", patch),
  stats: () => ipcRenderer.invoke("app:stats"),
  dragBegin: () => ipcRenderer.invoke("win:drag-begin"),
  dragTo: () => ipcRenderer.invoke("win:drag-to"),
  dragEnd: () => ipcRenderer.invoke("win:drag-end"),
  setIgnore: (v) => ipcRenderer.invoke("win:set-ignore", v),
  resize: (w, h) => ipcRenderer.invoke("win:resize", { w, h }),
  restoreSize: () => ipcRenderer.invoke("win:restore"),
  setupMode: (on) => ipcRenderer.invoke("win:setup-mode", on),
  showMenu: () => ipcRenderer.invoke("app:menu"),
  move: (dx, dy) => ipcRenderer.invoke("win:move", { dx, dy }),
  quit: () => ipcRenderer.invoke("win:quit"),
  openApp: (name) => ipcRenderer.invoke("app:open", name),
  openUrl: (url) => ipcRenderer.invoke("app:url", url),
  screenshot: () => ipcRenderer.invoke("app:screenshot"),
  chat: (messages) => ipcRenderer.invoke("chat:send", messages),
  transcribe: (wavBase64, lang) => ipcRenderer.invoke("voice:transcribe", { wav: wavBase64, lang }),
  debugState: () => ipcRenderer.invoke("debug:state"),
  onVoiceToggle: (cb) => ipcRenderer.on("voice:toggle", () => cb()),
  // real-time log (renderer -> %APPDATA%\zumi-desktop-buddy\zumi.log)
  log: (msg) => ipcRenderer.send("log:add", msg),
  logRead: (limit) => ipcRenderer.invoke("log:read", limit),
  // local brain (everything stored on this PC)
  brainStats: () => ipcRenderer.invoke("brain:stats"),
  memory: (q) => ipcRenderer.invoke("brain:memory", q),
  remember: (text, tag) => ipcRenderer.invoke("brain:remember", { text, tag }),
  forget: (q) => ipcRenderer.invoke("brain:forget", q),
  history: (limit) => ipcRenderer.invoke("brain:history", limit),
  historyAdd: (role, content) => ipcRenderer.invoke("brain:history-add", { role, content }),
  historyClear: () => ipcRenderer.invoke("brain:history-clear"),
  tasks: () => ipcRenderer.invoke("brain:tasks"),
  taskAdd: (t) => ipcRenderer.invoke("brain:task-add", t),
  taskDone: (q) => ipcRenderer.invoke("brain:task-done", q),
  taskRemove: (q) => ipcRenderer.invoke("brain:task-remove", q),
  notes: () => ipcRenderer.invoke("brain:notes"),
  noteAdd: (t) => ipcRenderer.invoke("brain:note-add", t),
  notesClear: () => ipcRenderer.invoke("brain:notes-clear"),
  reminders: () => ipcRenderer.invoke("brain:reminders"),
  reminderAdd: (text, at) => ipcRenderer.invoke("brain:reminder-add", { text, at }),
  reminderRemove: (q) => ipcRenderer.invoke("brain:reminder-remove", q),
  onReminder: (cb) => ipcRenderer.on("reminder:fire", (_e, r) => cb(r)),
  // extra skills
  clipGet: () => ipcRenderer.invoke("clip:get"),
  clipSet: (t) => ipcRenderer.invoke("clip:set", t),
  notify: (title, body) => ipcRenderer.invoke("notify", { title, body }),
  openPath: (p) => ipcRenderer.invoke("openPath", p),
  weather: (city) => ipcRenderer.invoke("weather", city),
  // ---- agent / task engine ----
  taskPlan: (instruction) => ipcRenderer.invoke("task:plan", instruction),
  taskList: () => ipcRenderer.invoke("task:list"),
  taskStats: () => ipcRenderer.invoke("task:stats"),
  taskReport: () => ipcRenderer.invoke("task:report"),
  taskRun: (id, confirmed) => ipcRenderer.invoke("task:run", { id, confirmed }),
  taskCancel: (id) => ipcRenderer.invoke("task:cancel", id),
  taskClear: () => ipcRenderer.invoke("task:clear"),
  taskLog: (limit) => ipcRenderer.invoke("task:log", limit),
  schedAdd: (task, schedule) => ipcRenderer.invoke("sched:add", { task, schedule }),
  schedList: () => ipcRenderer.invoke("sched:list"),
  schedRemove: (id) => ipcRenderer.invoke("sched:remove", id),
  ocrAvailable: () => ipcRenderer.invoke("automation:ocr-available"),
  dailyReport: () => ipcRenderer.invoke("daily:report"),
  onDailyReport: (cb) => ipcRenderer.on("daily:report", (_e, p) => cb(p)),
  onTaskUpdate: (cb) => ipcRenderer.on("task:update", (_e, p) => cb(p)),
  onTaskThinking: (cb) => ipcRenderer.on("task:thinking", (_e, p) => cb(p)),
  onTaskSpeak: (cb) => ipcRenderer.on("task:speak", (_e, p) => cb(p)),
  onScheduleFire: (cb) => ipcRenderer.on("task:schedule-fire", (_e, p) => cb(p)),
  // ---- batch engine ----
  batchRun: (count) => ipcRenderer.invoke("batch:run", count),
  batchStatus: () => ipcRenderer.invoke("batch:status"),
  onBatchProgress: (cb) => ipcRenderer.on("batch:progress", (_e, p) => cb(p)),
  onBatchDone: (cb) => ipcRenderer.on("batch:done", (_e, p) => cb(p)),
  // ---- coding batch (write + run code) ----
  codeRun: (count, run, concurrency, sub) => ipcRenderer.invoke("code:run", { count, run, concurrency, sub }),
  codeStatus: () => ipcRenderer.invoke("code:status"),
  codeOpenVscode: () => ipcRenderer.invoke("code:open-vscode"),
  onCodeProgress: (cb) => ipcRenderer.on("code:progress", (_e, p) => cb(p)),
  onCodeDone: (cb) => ipcRenderer.on("code:done", (_e, p) => cb(p)),
});
